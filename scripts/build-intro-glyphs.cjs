// Build actual TrueType contours for the intro mask; no browser font-parser dependency.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const b = fs.readFileSync(path.join(root, 'assets/fonts/ArchivoBlack-Regular.ttf'));
const u16 = p => b.readUInt16BE(p), i16 = p => b.readInt16BE(p), u32 = p => b.readUInt32BE(p);
const tables = {};
for (let i = 0; i < u16(4); i++) { const p = 12 + i * 16; tables[b.toString('ascii', p, p + 4)] = u32(p + 8); }
const em = u16(tables.head + 18), longLoca = i16(tables.head + 50), metrics = u16(tables.hhea + 34);
let cmap;
for (let i = 0; i < u16(tables.cmap + 2); i++) { const p = tables.cmap + 4 + i * 8; const sub = tables.cmap + u32(p + 4); if (u16(sub) === 4) cmap = sub; }
if (!cmap) throw Error('Expected a format-4 character map');
function glyphId(code) {
  const n = u16(cmap + 6) / 2, end = cmap + 14, start = end + 2 * n + 2, delta = start + 2 * n, range = delta + 2 * n;
  for (let i = 0; i < n; i++) if (code >= u16(start + 2 * i) && code <= u16(end + 2 * i)) {
    const r = u16(range + 2 * i), d = i16(delta + 2 * i);
    const id = r ? u16(range + 2 * i + r + 2 * (code - u16(start + 2 * i))) : code;
    return id ? (id + d) & 65535 : 0;
  }
  return 0;
}
function outline(id) {
  const loc = g => longLoca ? u32(tables.loca + g * 4) : u16(tables.loca + g * 2) * 2;
  if (loc(id) === loc(id + 1)) return '';
  let p = tables.glyf + loc(id), contours = i16(p); p += 10;
  if (contours < 0) throw Error('Composite glyph is not needed by this intro');
  const ends = [];
  for (let i = 0; i < contours; i++) { ends.push(u16(p)); p += 2; }
  const count = ends.at(-1) + 1, instructions = u16(p); p += 2 + instructions;
  const flags = [];
  while (flags.length < count) { const f = b[p++]; flags.push(f); if (f & 8) { const repeat = b[p++]; for (let j = 0; j < repeat; j++) flags.push(f); } }
  const xs = [], ys = []; let x = 0, y = 0;
  for (const f of flags) { if (f & 2) { const d = b[p++]; x += f & 16 ? d : -d; } else if (!(f & 16)) { x += i16(p); p += 2; } xs.push(x); }
  for (const f of flags) { if (f & 4) { const d = b[p++]; y += f & 32 ? d : -d; } else if (!(f & 32)) { y += i16(p); p += 2; } ys.push(-y); }
  let first = 0, d = '';
  for (const end of ends) {
    const pts = []; for (let i = first; i <= end; i++) pts.push({x:xs[i], y:ys[i], on:!!(flags[i] & 1)});
    const a = pts[0], z = pts.at(-1), origin = a.on ? a : z.on ? z : {x:(a.x+z.x)/2, y:(a.y+z.y)/2};
    d += `M${origin.x} ${origin.y}`;
    const seq = a.on ? pts.slice(1) : z.on ? pts.slice(0,-1) : pts;
    for (let i = 0; i < seq.length; i++) { const q = seq[i], next = seq[i+1] || origin;
      if (q.on) d += `L${q.x} ${q.y}`;
      else if (next.on !== false) { d += `Q${q.x} ${q.y} ${next.x} ${next.y}`; i++; }
      else d += `Q${q.x} ${q.y} ${(q.x+next.x)/2} ${(q.y+next.y)/2}`;
    }
    d += 'Z'; first = end + 1;
  }
  return d;
}
const glyphs = {};
for (const char of new Set('A BEGINNINGWITHOUTEND.')) { const id = glyphId(char.codePointAt(0)); glyphs[char] = {d:outline(id), advance:u16(tables.hmtx + Math.min(id, metrics - 1) * 4)}; }
fs.writeFileSync(path.join(root, 'intro-glyphs.js'), `// Generated by scripts/build-intro-glyphs.cjs from the licensed Archivo Black font.\nwindow.IntroGlyphs=${JSON.stringify({em,glyphs})};\n`);
console.log(`Built ${Object.keys(glyphs).length} real glyph outlines`);
